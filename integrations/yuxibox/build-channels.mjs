// Run: node integrations/yuxibox/build-channels.mjs
// Outputs disabled channel templates; no credentials, database or network access.
import {readFile, writeFile} from 'node:fs/promises';
const read = name => readFile(new URL(name, import.meta.url), 'utf8');
const [request_script, response_script, query_script] = await Promise.all([
    read('request.js'), read('response.js'), read('query.js'),
]);
const models = [
    ['seedance-2.5（YX）', 'video', 300000],
    ['seedance-2.5（YX）-按次', 'count', 3500000],
    ['seedance-2.0（官渠）', 'count', 2600000],
    ['seedance-2.0（YX）', 'video', 250000],
    // User confirmed 4 CNY/call on 2026-10-19 (the provider prose is stale).
    ['seedance2.5-yx-count', 'count', 4000000],
];
const descriptions = {
    'seedance-2.5（YX）': '5–30秒 | 默认30秒 | 最多30张参考图 / 10条参考视频 / 10条参考音频 | 固定720P',
    'seedance-2.5（YX）-按次': '固定30秒 | 最多30张参考图 / 10条参考视频 / 10条参考音频 | 固定720P',
    'seedance-2.0（官渠）': '4–15秒 | 默认15秒 | 最多9张参考图 / 3条参考音频 | 不支持参考视频 | 固定720P',
    'seedance-2.0（YX）': '5/10/15秒 | 默认15秒 | 最多9张参考图 / 3条参考视频 / 3条参考音频 | 固定720P',
    'seedance2.5-yx-count': '5–30秒 | 默认30秒 | 最多30张参考图 / 10条参考视频 / 10条参考音频 | 固定720P',
};
const channels = models.map(([model, billing_type, price]) => {
    const billing_config = {normalize_request: true};
    if (price !== null) {
        const unit = billing_type === 'video' ? 'second' : 'call';
        billing_config[`price_per_${unit}`] = price * 17 / 10;
        billing_config[`cost_per_${unit}`] = price;
    }
    return {
        name: `YuxiBox - ${model}`, model, display_name: model, type: 'video',
        base_url: 'https://yuxibox.cn/v1/videos', method: 'POST',
        headers: {'Authorization': 'Bearer {{pool_key}}', 'Content-Type': 'application/json'},
        timeout_ms: 120000, query_url: 'https://yuxibox.cn/v1/videos/{id}',
        query_method: 'GET', query_timeout_ms: 30000,
        request_script, response_script, query_script,
        billing_type, billing_config, key_pool_id: 0, protocol: 'openai',
        is_active: false, weight: 1, priority: 0,
        description: descriptions[model],
    };
});
await writeFile(new URL('channels.json', import.meta.url), JSON.stringify(channels, null, 2) + '\n');
const quote = v => "'" + String(v).replaceAll("'", "''") + "'";
const columns = Object.keys(channels[0]);
const sql = channels.map(ch => {
    const values = columns.map(k => typeof ch[k] === 'object' ? quote(JSON.stringify(ch[k])) + '::jsonb' :
        typeof ch[k] === 'string' ? quote(ch[k]) : String(ch[k]));
    return `INSERT INTO channels (${columns.join(', ')}, model_provider_id)\nSELECT ${values.join(', ')}, (SELECT id FROM model_providers WHERE name = 'Doubao' AND is_active)\nWHERE NOT EXISTS (SELECT 1 FROM channels WHERE name = ${quote(ch.name)});`;
}).join('\n\n');
await writeFile(new URL('seed.sql', import.meta.url), '-- Generated by build-channels.mjs. Inserts disabled channels only; preserves existing channels.\nBEGIN;\nDO $$ BEGIN IF (SELECT count(*) FROM model_providers WHERE name = \'Doubao\' AND is_active) <> 1 THEN RAISE EXCEPTION \'Exactly one active Doubao provider is required\'; END IF; END $$;\n' + sql + '\nCOMMIT;\n');
